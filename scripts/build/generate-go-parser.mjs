import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildParserFile } from "@lezer/generator";

// The upstream grammar is pinned; retain reviewed grammar/tokenizer patches.
// No source normalization, runtime compiler, or parser-error suppression.
const require = createRequire(import.meta.url);
const args = process.argv.slice(2);
if (args.some(arg => arg !== "--check")) throw new Error("Only --check is supported.");
const checkOnly = args.includes("--check");
const upstreamRoot = resolve(dirname(require.resolve("@lezer/go")), "..");
const upstream = JSON.parse(await readFile(resolve(upstreamRoot, "package.json"), "utf8"));
if (upstream.version !== "1.0.1") throw new Error("Review the Go grammar patch before updating @lezer/go.");
const readUpstream = async name => (await readFile(resolve(upstreamRoot, name), "utf8")).replace(/\r\n/g, "\n");
const grammar = await readUpstream("src/go.grammar");
const before = 'RangeClause { (exprList "=" | idList ":=") kw<"range"> expr }';
const after = 'RangeClause { (exprList "=" | idList ":=")? kw<"range"> expr }';
if (grammar.split(before).length !== 2) throw new Error("Expected exactly one upstream RangeClause production.");
const booleanBefore = 'Bool { @specialize<identifier, "true" | "false"> }';
const booleanAfter = 'Bool { @specialize[@export=boolLiteral]<identifier, "true" | "false"> }';
if (grammar.split(booleanBefore).length !== 2) throw new Error("Expected exactly one upstream Bool production.");
const patched = grammar.replace(before, after).replace(booleanBefore, booleanAfter)
  .replaceAll('from "./tokens"', 'from "./tokens.js"')
  .replaceAll('from "./highlight"', 'from "./highlight.js"');
const generated = buildParserFile(patched, { typeScript: true });
const tokens = await readUpstream("src/tokens.js");
const trackedBefore = "IncDecOp, identifier, Rune";
if (tokens.split(trackedBefore).length !== 3) throw new Error("Expected the upstream token import and semicolon tracking set.");
const patchedTokens = tokens.replaceAll(trackedBefore, "IncDecOp, identifier, boolLiteral, Rune");
const license = await readUpstream("LICENSE");
const header = `/* Generated by scripts/build/generate-go-parser.mjs from @lezer/go 1.0.1.
 * Local patches: optional range-clause binding and boolean semicolon tracking.
 * Regenerate instead of editing this file.
\n${license}\n*/\n`;
const directory = fileURLToPath(new URL("../../src/extraction/go-parser/", import.meta.url));
if (!checkOnly) await mkdir(directory, { recursive: true });
for (const [name, text] of [
  ["parser.ts", generated.parser],
  ["parser.terms.ts", generated.terms],
  ["tokens.ts", patchedTokens],
  ["highlight.ts", await readUpstream("src/highlight.js")]
]) {
  const path = resolve(directory, name);
  const content = header + text;
  const previous = await readFile(path, "utf8").catch(error => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (previous?.replace(/\r\n/g, "\n") !== content) {
    if (checkOnly) throw new Error(`Generated Go parser is out of date: ${name}`);
    await writeFile(path, content);
  }
}
